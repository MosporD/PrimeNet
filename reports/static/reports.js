const REPORT_META = {
    site_inventory:      { icon: '🏗️', desc: 'All active sites and cells with location, azimuth, PCI, tilt, and band data.' },
    pci_conflicts:       { icon: '⚠️', desc: 'PCI/PSC/BCCH conflicts across sites — groups of cells with duplicate identifiers.' },
    performance_summary: { icon: '📈', desc: 'Latest hourly KPI snapshot for all cells from Nokia and Huawei PM databases.' },
    config_versions:     { icon: '📋', desc: 'Full log of all XML configuration versions uploaded to the version history module.' },
};

window.addEventListener('DOMContentLoaded', () => {
    loadReportTypes();
    loadArchive();
});

async function loadReportTypes() {
    const res  = await fetch('/api/reports/types');
    const data = await res.json();
    if (!data.success) return;

    const container = document.getElementById('reportCards');
    container.innerHTML = data.types.map(t => {
        const meta = REPORT_META[t.id] || { icon: '📊', desc: '' };
        return `
        <div class="report-card" id="card-${t.id}" onclick="generateReport('${t.id}', '${t.label}')">
            <div class="report-icon">${meta.icon}</div>
            <div class="report-title">${t.label}</div>
            <div class="report-desc">${meta.desc}</div>
        </div>`;
    }).join('');
}

async function generateReport(type, label) {
    const card = document.getElementById('card-' + type);
    card.classList.add('generating');
    card.innerHTML += `<div class="report-gen-overlay"><span class="loading-spinner" style="width:22px;height:22px;border-width:3px"></span> Generating…</div>`;

    const statusEl = document.getElementById('generateStatus');
    statusEl.className = 'status-message info';
    statusEl.textContent = `Generating ${label}…`;

    try {
        const res  = await fetch('/api/reports/generate', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ report_type: type })
        });
        const data = await res.json();

        if (data.success) {
            statusEl.className = 'status-message success';
            statusEl.textContent = `✓ ${label} generated (${data.rows.toLocaleString()} rows). Downloading…`;
            window.location.href = `/api/reports/download/${data.archive_id}`;
            loadArchive();
        } else {
            statusEl.className = 'status-message error';
            statusEl.textContent = data.error || 'Report generation failed';
        }
    } catch (e) {
        statusEl.className = 'status-message error';
        statusEl.textContent = 'Network error. Please try again.';
    }

    // Re-load card (removes overlay)
    card.classList.remove('generating');
    loadReportTypes();
}

async function loadArchive() {
    const container = document.getElementById('archiveContainer');
    const res  = await fetch('/api/reports/archive');
    const data = await res.json();
    const reports = data.reports || [];

    if (!reports.length) {
        container.innerHTML = '<div class="empty-archive">No reports generated yet. Click a report card above to generate one.</div>';
        return;
    }

    container.innerHTML = `
    <div class="archive-table-wrapper">
        <table class="archive-table">
            <thead><tr>
                <th>Report Name</th>
                <th>Type</th>
                <th>Size</th>
                <th>Generated At</th>
                <th>Generated By</th>
                <th>Actions</th>
            </tr></thead>
            <tbody>
                ${reports.map(r => `
                <tr>
                    <td>${r.report_name}</td>
                    <td><span class="type-badge">${r.report_type}</span></td>
                    <td>${formatSize(r.file_size)}</td>
                    <td>${r.generated_at ? r.generated_at.slice(0,16) : '—'}</td>
                    <td>${r.generated_by_name || '—'}</td>
                    <td style="white-space:nowrap">
                        <button class="btn-dl" onclick="downloadReport(${r.id})">⬇ Download</button>
                        <button class="btn-rm" onclick="deleteReport(${r.id})">🗑 Delete</button>
                    </td>
                </tr>`).join('')}
            </tbody>
        </table>
    </div>`;
}

function downloadReport(id) {
    window.location.href = `/api/reports/download/${id}`;
}

async function deleteReport(id) {
    if (!confirm('Remove this report from the archive?')) return;
    const res  = await fetch(`/api/reports/archive/${id}`, { method: 'DELETE' });
    const data = await res.json();
    if (data.success) loadArchive();
}

function formatSize(bytes) {
    if (!bytes) return '—';
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1048576) return (bytes / 1024).toFixed(1) + ' KB';
    return (bytes / 1048576).toFixed(1) + ' MB';
}
